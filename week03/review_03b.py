# math八函数
from math import *
s=25.5
print(abs(s)) # 25.5
print(pow(s,3)) # 16581.375
print(round(s,1)) # 25.5
print(sqrt(s)) # 5.049752469181039
print(ceil(s)) # 26
print(floor(s)) # 25
print(pi) # 3.141592653589793
print(sin(pi/2)) # 1.0

