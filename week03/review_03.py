import math
# 取整：天花板ceil、地板floor、四舍五入round
print(math.ceil(3.2))
print(math.floor(3.8))
print(round(2.5))

# 幂和根3个：内置幂、开方sqrt、勾股斜边hypot
print(2**3)
print(math.sqrt(16))
print(math.hypot(3,4))

# 常量、三角2个：圆周率pi、正弦sin）
print(math.pi)
print(math.sin(math.pi/2))

# 绝对值abs
print(abs(-10))
print(abs(10))

# 幂余
print(pow(2,3))


